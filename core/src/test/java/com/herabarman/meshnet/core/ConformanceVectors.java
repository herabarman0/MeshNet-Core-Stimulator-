package com.herabarman.meshnet.core;

import java.io.BufferedWriter;
import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Random;

/**
 * Generates conformance/vectors.txt: language-neutral test vectors that any port of the engine (C++, Rust, Zig, ...)
 * must reproduce bit for bit. The Java engine is the reference.
 *
 * Lines:
 *   packet HEX type attempt ttl priority msgId src dst srcZone dstZone   (decode must give these fields, encode must give HEX)
 *   bad HEX                                                                (decode must fail)
 *   home nodeId zoneCount expectedZone                                     (LocationDirectory.homeZone)
 *
 * Usage: java -cp ... com.herabarman.meshnet.core.ConformanceVectors conformance/vectors.txt
 */
public final class ConformanceVectors {
    private ConformanceVectors() {}

    static String hex(byte[] b) {
        StringBuilder sb = new StringBuilder(b.length * 2);
        for (byte x : b) sb.append(String.format("%02x", x & 0xFF));
        return sb.toString();
    }

    public static List<String> generate() {
        Random r = new Random(20261122L);
        List<String> out = new ArrayList<>();
        int[] types = {0, 1, 2, 3, 4, 5, 6, 15};
        int[] lens = {0, 1, 2, 7, 29, 30, 31, 255, 256, 1000, 4096};
        int[] ids = {0, 1, -1, 42, Integer.MAX_VALUE, Integer.MIN_VALUE, Packet.zoneAddress(7), Packet.zoneAddress(1_000_000)};
        int[] zones = {Packet.UNKNOWN_ZONE, 0, 1, 39, 66665, Integer.MAX_VALUE};
        long[] mids = {0L, 1L, -1L, Long.MAX_VALUE, Long.MIN_VALUE};
        for (int i = 0; i < 400; i++) {
            byte[] payload = new byte[lens[r.nextInt(lens.length)]];
            r.nextBytes(payload);
            long msgId = i < mids.length ? mids[i] : r.nextLong();
            Packet p = new Packet(types[r.nextInt(types.length)], r.nextInt(256), r.nextInt(256), msgId,
                    r.nextBoolean() ? ids[r.nextInt(ids.length)] : r.nextInt(), r.nextBoolean() ? ids[r.nextInt(ids.length)] : r.nextInt(),
                    payload, r.nextInt(16), r.nextBoolean() ? zones[r.nextInt(zones.length)] : r.nextInt(),
                    r.nextBoolean() ? zones[r.nextInt(zones.length)] : r.nextInt());
            out.add("packet " + hex(p.encode()) + " " + p.type + " " + p.attempt + " " + p.ttl + " " + p.priority + " "
                    + p.msgId + " " + p.src + " " + p.dst + " " + p.srcZone + " " + p.dstZone);
        }
        // largest payload once
        byte[] big = new byte[Packet.MAX_PAYLOAD];
        r.nextBytes(big);
        Packet bp = new Packet(Packet.TYPE_DATA, 255, 255, -7L, 1, 2, big, 15, 3, 4);
        out.add("packet " + hex(bp.encode()) + " 1 15 255 255 -7 1 2 3 4");

        byte[] good = new Packet(1, 5, 1, 99L, 1, 2, new byte[]{9, 8, 7}, 0, 1, 2).encode();
        out.add("bad ");                                              // empty
        out.add("bad " + hex(java.util.Arrays.copyOf(good, 29)));     // shorter than a header
        out.add("bad " + hex(java.util.Arrays.copyOf(good, good.length - 1))); // payload shorter than declared
        byte[] longer = java.util.Arrays.copyOf(good, good.length + 1);
        out.add("bad " + hex(longer));                                // payload longer than declared
        byte[] oldVersion = good.clone();
        oldVersion[0] = 1;
        out.add("bad " + hex(oldVersion));
        byte[] zeroVersion = good.clone();
        zeroVersion[0] = 0;
        out.add("bad " + hex(zeroVersion));

        int[] homeIds = {0, 1, 2, 3, -1, -2, Integer.MAX_VALUE, Integer.MIN_VALUE, 12345, 65535, 65536};
        int[] counts = {1, 2, 3, 10, 40, 64, 1000, 66_666, 1_000_000, Integer.MAX_VALUE};
        for (int id : homeIds) for (int c : counts) out.add("home " + id + " " + c + " " + LocationDirectory.homeZone(id, c));
        for (int i = 0; i < 3000; i++) {
            int id = r.nextInt();
            int c = 1 + r.nextInt(r.nextBoolean() ? 100 : Integer.MAX_VALUE - 1);
            out.add("home " + id + " " + c + " " + LocationDirectory.homeZone(id, c));
        }
        return out;
    }

    public static void main(String[] args) throws IOException {
        File f = new File(args.length > 0 ? args[0] : "conformance/vectors.txt");
        BufferedWriter w = new BufferedWriter(new FileWriter(f));
        try {
            w.write("# MeshNet conformance vectors, generated by ConformanceVectors.java (the Java engine is the reference). Do not edit.\n");
            for (String line : generate()) w.write(line + "\n");
        } finally {
            w.close();
        }
        System.out.println("wrote " + f.getPath());
    }
}
